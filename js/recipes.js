const parse = (s) => s.split(';').map((x) => {
  const [name, qty = ''] = x.split('|').map((t) => t.trim());
  return { name, qty };
});

/** Ingredients (parsed), method and source for a dish, or null if we haven't checked its video yet. */
const BY_KEY = new Map(Object.entries(RECIPES).map(([name, r]) => [name.toLowerCase().trim(), r]));

export function recipeFor(name) {
  const r = BY_KEY.get(String(name || '').toLowerCase().trim());
  return r ? { ingredients: parse(r.ingredients), method: [...r.method], recipeFrom: r.from } : null;
}

